#!/usr/bin/env python3
"""Write two 31-stage ring oscillators, one from each inverter.

An odd-length ring of inverters cannot settle: whatever it does, the loop
disagrees with itself half a lap later, so it oscillates. Its period is
2 * N * (one stage delay), which makes it the cleanest possible measurement of
how fast a single gate is - no input source, no load, nothing but the cell
driving one copy of itself.
"""
from __future__ import annotations

from ports import RESULTS, connect, my_inv_ports

N = 31

HEAD = """* Lab 05 - two 31-stage ring oscillators, generated by src/mkring.py
.lib $PDK_ROOT/sky130A/libs.tech/ngspice/sky130.lib.spice tt
.include my_inv.pex.spice
.include sky130_fd_sc_hd__inv_1.pex.spice
Vdd VPWR 0 1.8
"""

TAIL = f"""
.ic v(f01)=0 v(m01)=0
.tran 2p 20n uic
.meas tran fper TRIG v(f01) VAL=0.9 RISE=3 TARG v(f01) VAL=0.9 RISE=5
.meas tran mper TRIG v(m01) VAL=0.9 RISE=3 TARG v(m01) VAL=0.9 RISE=5
.end
"""


def main() -> None:
    ports = my_inv_ports()
    lines = [HEAD, f"* the foundry's cell, {N} stages\n"]
    for i in range(1, N + 1):
        a, b = f"f{i:02d}", f"f{(i % N) + 1:02d}"
        lines.append(f"Xf{i:02d} {a} 0 0 VPWR VPWR {b} sky130_fd_sc_hd__inv_1\n")
    lines.append(f"\n* yours, {N} stages\n")
    for i in range(1, N + 1):
        a, b = f"m{i:02d}", f"m{(i % N) + 1:02d}"
        lines.append(f"Xm{i:02d} {connect([a, b, 'VPWR', '0'], ports)} my_inv\n")
    lines.append(TAIL)
    (RESULTS / "ring.spice").write_text("".join(lines))
    print(f"   wrote results/ring.spice  ({N} stages each)")


if __name__ == "__main__":
    main()
